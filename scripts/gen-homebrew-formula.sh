#!/usr/bin/env bash
# Generate the Homebrew formula for a release, with real checksums filled in.
#
# mislav/bump-homebrew-formula-action can only update a single url+sha256 pair,
# but this formula has four platform blocks (darwin/linux x arm64/x64), so it
# cannot express this release. This script reads the SHA256SUMS produced by
# build-binaries.sh and writes a complete formula instead.
#
# Usage: bash scripts/gen-homebrew-formula.sh <version> [sums-file] [out-file]
#   version:    release version WITHOUT the leading 'v' (e.g. 0.2.0)
#   sums-file:  defaults to dist-bin/SHA256SUMS
#   out-file:   defaults to dist-bin/sendlayer.rb
set -euo pipefail

VERSION="${1:?version required (e.g. 0.2.0)}"
VERSION="${VERSION#v}"
SUMS_FILE="${2:-dist-bin/SHA256SUMS}"
OUT_FILE="${3:-dist-bin/sendlayer.rb}"
REPO="${SENDLAYER_REPO:-SendLayer/sendlayer-cli}"

if [ ! -f "$SUMS_FILE" ]; then
  echo "Checksum file not found: $SUMS_FILE (run build-binaries.sh first)" >&2
  exit 1
fi

# Look up the checksum for one archive, failing loudly if it is absent —
# a formula with a missing sha256 would fail for users at install time.
sha_for() {
  local archive="$1" sum
  sum="$(awk -v a="$archive" '$2 == a {print $1}' "$SUMS_FILE")"
  if [ -z "$sum" ]; then
    echo "No checksum for $archive in $SUMS_FILE" >&2
    exit 1
  fi
  printf '%s' "$sum"
}

DARWIN_ARM64="$(sha_for "sendlayer_${VERSION}_darwin_arm64.tar.gz")"
DARWIN_X64="$(sha_for "sendlayer_${VERSION}_darwin_x64.tar.gz")"
LINUX_ARM64="$(sha_for "sendlayer_${VERSION}_linux_arm64.tar.gz")"
LINUX_X64="$(sha_for "sendlayer_${VERSION}_linux_x64.tar.gz")"

mkdir -p "$(dirname "$OUT_FILE")"

cat > "$OUT_FILE" <<EOF
# Generated by scripts/gen-homebrew-formula.sh — do not edit by hand.
# Tap install: brew install sendlayer/sendlayer/sendlayer

class Sendlayer < Formula
  desc "Command-line interface for the SendLayer transactional email API"
  homepage "https://github.com/${REPO}"
  version "${VERSION}"
  license "MIT"

  on_macos do
    on_arm do
      url "https://github.com/${REPO}/releases/download/v#{version}/sendlayer_#{version}_darwin_arm64.tar.gz"
      sha256 "${DARWIN_ARM64}"
    end
    on_intel do
      url "https://github.com/${REPO}/releases/download/v#{version}/sendlayer_#{version}_darwin_x64.tar.gz"
      sha256 "${DARWIN_X64}"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/${REPO}/releases/download/v#{version}/sendlayer_#{version}_linux_arm64.tar.gz"
      sha256 "${LINUX_ARM64}"
    end
    on_intel do
      url "https://github.com/${REPO}/releases/download/v#{version}/sendlayer_#{version}_linux_x64.tar.gz"
      sha256 "${LINUX_X64}"
    end
  end

  def install
    bin.install "sendlayer"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sendlayer --version")
  end
end
EOF

echo "==> Wrote $OUT_FILE"
